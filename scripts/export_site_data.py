"""Export the aggregates used by the project website (docs/index.html) to docs/data.js.

Run from the repository root after the database has been extracted
(the notebook's setup cell does this):

    python scripts/export_site_data.py
"""
import json
import os
import sqlite3
import zipfile

import numpy as np
import pandas as pd

DB_PATH = os.path.join('data', 'anon_jobs.db3')
DATA_ZIP = os.path.join('data', 'gwa_t_4_anon_jobs_sqlite.zip')
OUT_PATH = os.path.join('docs', 'data.js')


def log_hist(values, lo, hi, n_bins):
    """Histogram on log-spaced bins; returns bin edges and counts."""
    edges = np.logspace(np.log10(lo), np.log10(hi), n_bins + 1)
    counts, _ = np.histogram(np.clip(values, lo, hi * 0.999999), bins=edges)
    return {'edges': [float(f'{e:.6g}') for e in edges], 'counts': counts.tolist()}


def main():
    if not os.path.exists(DB_PATH):
        with zipfile.ZipFile(DATA_ZIP) as z:
            z.extract('anon_jobs.db3', 'data')

    con = sqlite3.connect(DB_PATH)
    df = pd.read_sql_query(
        'SELECT SubmitTime, WaitTime, RunTime, ReqTime, ReqMemory, UsedMemory, '
        'Status, UserID FROM Jobs', con)
    con.close()

    ran = df[df['RunTime'] > 0]
    waited = df[df['WaitTime'] > 0]

    mem = df[(df['ReqMemory'] > 0) & (df['RunTime'] > 0)]
    mem_ratio = (mem['UsedMemory'] / mem['ReqMemory']).clip(0, 1)
    mem_counts, mem_edges = np.histogram(mem_ratio, bins=40, range=(0, 1))

    rt = df[(df['ReqTime'] > 0) & (df['RunTime'] > 0)]
    time_ratio = rt['RunTime'] / rt['ReqTime']

    submit = pd.to_datetime(df['SubmitTime'], unit='s', utc=True).dt.tz_convert('Europe/Paris')
    per_user = df['UserID'].value_counts()
    cum_share = (per_user.cumsum() / per_user.sum()).round(4)

    status = df['Status'].value_counts(normalize=True)

    data = {
        'summary': {
            'jobs': int(len(df)),
            'users': int(per_user.size),
            'start': str(submit.min().date()),
            'end': str(submit.max().date()),
            'median_run_s': float(ran['RunTime'].median()),
            'mean_run_s': float(ran['RunTime'].mean()),
            'median_wait_s': float(df['WaitTime'].median()),
            'mean_wait_s': float(df['WaitTime'].mean()),
            'share_wait_under_1min': float((df['WaitTime'] < 60).mean()),
            'completed': float(status.get(1, 0)),
            'cancelled': float(status.get(5, 0)),
            'failed': float(status.get(0, 0)),
            'mem_jobs': int(len(mem)),
            'mem_mean': float(mem_ratio.mean()),
            'mem_median': float(mem_ratio.median()),
            'mem_under_10pct': float((mem_ratio < 0.1).mean()),
            'time_jobs': int(len(rt)),
            'time_median': float(time_ratio.median()),
            'time_under_10pct': float((time_ratio < 0.1).mean()),
            'limit_72h_share': float((rt['ReqTime'] == 72 * 3600).mean()),
            'limit_96h_share': float((rt['ReqTime'] == 96 * 3600).mean()),
            'top1_share': float(cum_share.iloc[0]),
            'top10_share': float(cum_share.iloc[9]),
            'users_for_80pct': int((cum_share < 0.8).sum()) + 1,
        },
        'runtime': log_hist(ran['RunTime'], 1, 2e6, 48),
        'wait': log_hist(waited['WaitTime'], 1, 5e6, 48),
        'memory': {'edges': mem_edges.round(4).tolist(), 'counts': mem_counts.tolist()},
        'time_ratio': log_hist(time_ratio, 1e-6, 100, 48),
        'monthly': submit.dt.month.value_counts().sort_index().tolist(),
        'hourly': submit.dt.hour.value_counts().sort_index().tolist(),
        'weekday': submit.dt.dayofweek.value_counts().sort_index().tolist(),
        'user_cum_share': cum_share.tolist(),
    }

    os.makedirs('docs', exist_ok=True)
    with open(OUT_PATH, 'w') as f:
        f.write('// Generated by scripts/export_site_data.py - do not edit by hand.\n')
        f.write('window.WORKLOAD_DATA = ')
        json.dump(data, f, separators=(',', ':'))
        f.write(';\n')
    print(f'Wrote {OUT_PATH}')


if __name__ == '__main__':
    main()
